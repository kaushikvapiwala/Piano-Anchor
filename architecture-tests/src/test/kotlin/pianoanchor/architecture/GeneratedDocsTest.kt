package pianoanchor.architecture

import com.lemonappdev.konsist.api.declaration.KoFunctionDeclaration
import com.lemonappdev.konsist.api.declaration.KoKDocDeclaration
import com.lemonappdev.konsist.api.declaration.KoPropertyDeclaration
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import pianoanchor.architecture.Sources.PORTS
import pianoanchor.architecture.Sources.ports
import pianoanchor.architecture.Sources.tunables
import java.io.File

/**
 * Golden tests for `docs/generated/`: each file must equal what the code renders, so a stale file or a hand edit
 * fails the build. `./gradlew generateDocs` sets [UPDATE_PROPERTY] and rewrites the files instead.
 */
class GeneratedDocsTest {
    private companion object {
        const val UPDATE_PROPERTY = "pianoanchor.updateGeneratedDocs"
        const val TUNABLES_SOURCE = "engine/src/commonMain/kotlin/pianoanchor/engine/Tunables.kt"

        // Gradle runs tests with the module directory as working directory.
        val repoRoot: File = File("").absoluteFile.parentFile

        val blankLines = Regex("\\n\\s*\\n")
        val whitespace = Regex("\\s+")

        fun String.oneLine() = trim().replace(whitespace, " ")

        fun String.cell() = oneLine().replace("|", "\\|")

        /** KDoc text without comment markers and block tags (everything from the first `@` line on). */
        fun KoKDocDeclaration?.body(): String =
            this
                ?.text
                .orEmpty()
                .removePrefix("/**")
                .removeSuffix("*/")
                .lines()
                .map { it.trim().trimStart('*').trim() }
                .takeWhile { !it.startsWith("@") }
                .joinToString("\n")
                .trim()

        fun paragraphs(text: String) = text.split(blankLines).map { it.oneLine() }.filter { it.isNotEmpty() }

        /** The value as written in source (not parsed from [KoPropertyDeclaration.text], which includes the KDoc). */
        fun KoPropertyDeclaration.initializer() = value.orEmpty().oneLine()

        fun KoFunctionDeclaration.signature(): String {
            val typeParams =
                typeParameters
                    .takeIf { it.isNotEmpty() }
                    ?.joinToString(", ", prefix = "<", postfix = "> ") { it.text.oneLine() }
                    .orEmpty()
            val receiver = receiverType?.sourceType?.let { "$it." }.orEmpty()
            val params =
                parameters.joinToString(", ") {
                    val vararg = if (it.hasVarArgModifier) "vararg " else ""
                    val default = it.defaultValue?.let { value -> " = ${value.oneLine()}" }.orEmpty()
                    "$vararg${it.name}: ${it.type.sourceType}$default"
                }
            val returns =
                returnType
                    ?.sourceType
                    ?.takeIf { it != "Unit" }
                    ?.let { ": $it" }
                    .orEmpty()
            val suspend = if (hasSuspendModifier) "suspend " else ""
            return "${suspend}fun $typeParams$receiver$name($params)$returns"
        }

        fun renderTunables(): String {
            val rows =
                tunables
                    .joinToString("\n") { property ->
                        val doc = property.kDoc.body()
                        val meaning = doc.substringBefore("Why:")
                        val why = doc.substringAfter("Why:", "").substringBefore("Source:")
                        val source = doc.substringAfter("Source:", "")
                        "| `${property.name}` | ${property.initializer().cell()} | ${meaning.cell()} | " +
                            "${why.cell()} | ${source.cell()} |"
                    }
            return """
                <!-- Generated by ./gradlew generateDocs from $TUNABLES_SOURCE. Do not edit by hand. -->
                # Tunables

                Every engine threshold, from the KDoc in `$TUNABLES_SOURCE`.

                | Name | Value | Meaning | Why | Source |
                |---|---|---|---|---|
                """.trimIndent() + "\n$rows\n"
        }

        fun contractTestPath(port: String): String {
            val file = Sources.contractTestFor(port)?.containingFile ?: return "missing"
            return "`${file.path.removePrefix(repoRoot.invariantSeparatorsPath).removePrefix("/")}`"
        }

        fun renderPorts(): String {
            val sections =
                ports
                    .sortedBy { it.name }
                    .joinToString("\n\n") { port ->
                        val members =
                            port.properties().map {
                                "`val ${it.name}: ${it.type?.sourceType}` | ${it.kDoc.body().cell()}"
                            } +
                                port.functions().map { "`${it.signature()}` | ${it.kDoc.body().cell()}" }
                        listOf(
                            "## `${port.name}`",
                            "",
                            paragraphs(port.kDoc.body()).joinToString("\n\n"),
                            "",
                            "| Function | Description |",
                            "|---|---|",
                        ).plus(members.map { "| $it |" })
                            .plus(listOf("", "Contract test: ${contractTestPath(port.name)}"))
                            .joinToString("\n")
                    }
            return """
                <!-- Generated by ./gradlew generateDocs from core/ports. Do not edit by hand. -->
                # Ports

                Every port interface in `$PORTS`, from its KDoc.

                """.trimIndent() + "\n$sections\n"
        }

        val generatedDir = File(repoRoot, "docs/generated")

        /** Every generated doc by file name; shared by the golden tests and the stray-file test. */
        fun rendered() = mapOf("tunables.md" to renderTunables(), "ports.md" to renderPorts())

        fun check(name: String) {
            assertTrue(File(repoRoot, "settings.gradle.kts").isFile) {
                "Cannot find the repo root: expected settings.gradle.kts in ${repoRoot.path}"
            }
            val rendered = rendered().getValue("$name.md")
            val file = File(generatedDir, "$name.md")
            if (System.getProperty(UPDATE_PROPERTY) == "true") {
                generatedDir.mkdirs()
                file.writeText(rendered)
            } else {
                assertEquals(rendered, file.takeIf { it.isFile }?.readText()) {
                    "docs/generated/$name.md is stale or was edited by hand. " +
                        "Run ./gradlew generateDocs and commit the result."
                }
            }
        }
    }

    @Test
    fun `tunables doc matches the code (run generateDocs to update)`() = check("tunables")

    @Test
    fun `ports doc matches the code (run generateDocs to update)`() = check("ports")

    @Test
    fun `docs generated folder has only generated files`() {
        val extra =
            generatedDir
                .listFiles { file -> file.extension == "md" }
                .orEmpty()
                .map { it.name }
                .toSet() - rendered().keys
        assertTrue(extra.isEmpty()) {
            "docs/generated/ has files no generator produces: ${extra.sorted()}. " +
                "Delete them or add a generator to GeneratedDocsTest."
        }
    }
}
