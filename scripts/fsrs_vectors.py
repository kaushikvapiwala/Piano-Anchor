"""Generate engine/src/commonTest/kotlin/pianoanchor/engine/scheduler/Fsrs6Vectors.kt with py-fsrs.

Run by hand only (never in CI):  pip install fsrs==6.3.3 && python3 scripts/fsrs_vectors.py
then ./gradlew spotlessApply (the committed file is ktlint-formatted).
The committed output is the golden data for FsrsVectorsTest. py-fsrs is MIT licensed (see NOTICE).
"""

import random
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

from fsrs import Card, Rating, Scheduler

PINNED = "6.3.3"
SEED = 20260101
SEQUENCES = 25
MAX_REVIEWS = 12
MAX_GAP_DAYS = 90
OUT = Path(__file__).resolve().parent.parent / (
    "engine/src/commonTest/kotlin/pianoanchor/engine/scheduler/Fsrs6Vectors.kt"
)
HEADER = """\
// GENERATED by scripts/fsrs_vectors.py from py-fsrs {version}. Do not edit by hand.
//
// py-fsrs: https://github.com/open-spaced-repetition/py-fsrs
// Copyright (c) 2022 open-spaced-repetition. MIT License (full text in the repository NOTICE file).
// Permission is granted, free of charge, to use, copy, modify and distribute this software and the
// data derived from it, provided this notice is kept in all copies or substantial portions.
// THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND.
package pianoanchor.engine.scheduler

import pianoanchor.core.model.Rating

internal val FSRS6_VECTORS: List<List<FsrsVectorStep>> = listOf(
"""


def main() -> None:
    from importlib.metadata import version as pkg_version

    version = pkg_version("fsrs")
    if version != PINNED:
        sys.exit(f"fsrs=={PINNED} required, found {version}")
    rng = random.Random(SEED)
    scheduler = Scheduler(
        learning_steps=(), relearning_steps=(), enable_fuzzing=False, desired_retention=0.9
    )
    ratings = [Rating.Again, Rating.Hard, Rating.Good, Rating.Easy]
    names = {Rating.Again: "AGAIN", Rating.Hard: "HARD", Rating.Good: "GOOD", Rating.Easy: "EASY"}
    out = [HEADER.format(version=version)]
    for _ in range(SEQUENCES):
        card = Card()
        now = datetime(2026, 1, 1, 9, 0, tzinfo=timezone.utc)
        out.append("    listOf(\n")
        for i in range(rng.randint(1, MAX_REVIEWS)):
            gap = 0
            r = None
            if i > 0:
                gap = rng.randint(1, MAX_GAP_DAYS)
                now += timedelta(days=gap)
                r = scheduler.get_card_retrievability(card, current_datetime=now)
            rating = rng.choice(ratings)
            card, _log = scheduler.review_card(card, rating, now)
            interval = (card.due - now).days
            rs = "null" if r is None else repr(r)
            out.append(
                f"        FsrsVectorStep(Rating.{names[rating]}, {gap}, {card.stability!r}, "
                f"{card.difficulty!r}, {rs}, {interval}),\n"
            )
        out.append("    ),\n")
    out.append(")\n")
    OUT.write_text("".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
